# одном месте на оба скрипта, чтобы они не разъехались.
#
# Требуется переменная MONITOR — путь к monitor.sh.
# ---------------------------------------------------------------------------

# Снимок ключей проблем.  kalitka_snimok <файл-для-ключей> <подпись>
# Возврат: 0 — снимок снят (проблемы в нём могут быть, это нормально),
#          2 — замер не удался, состояние сайта неизвестно.
kalitka_snimok() {
  local out=$1 podpis=$2 rc=0
  : "${MONITOR:?в вызывающем скрипте не задан MONITOR}"
  bash "$MONITOR" --keys >"$out" 2>"$out.err" || rc=$?
  if [ "$rc" -ge 2 ]; then
    echo "    ЗАМЕР НЕ УДАЛСЯ ($podpis), код $rc — состояние сайта неизвестно:"
    sed 's/^/      /' "$out.err"
    return 2
  fi
  local n; n=$(wc -l <"$out")
  if [ "$n" -eq 0 ]; then
    echo "    $podpis: проблем нет"
  else
    echo "    $podpis: проблем $n — $(tr '\n' ' ' <"$out")"
  fi
  return 0
}

# Сравнение двух снимков.  kalitka_sravnit <файл-до> <файл-после>
# Возврат: 0 — новых ключей нет, заливку можно оставить;
#          1 — появился ключ, которого до заливки не было.
kalitka_sravnit() {
  local do_f=$1 posle_f=$2 novye ushli
  novye=$(comm -13 <(sort -u "$do_f") <(sort -u "$posle_f"))
  ushli=$(comm -23 <(sort -u "$do_f") <(sort -u "$posle_f"))

  # Исчезнувшая проблема — это хорошо, а не повод для отката.
  if [ -n "$ushli" ]; then
    echo "    закрылись проблемы: $(tr '\n' ' ' <<<"$ushli")"
  fi
  if [ -z "$novye" ]; then
    echo "    новых проблем нет — прежние не в счёт"
    return 0
  fi
  echo "    ПОЯВИЛИСЬ НОВЫЕ ПРОБЛЕМЫ: $(tr '\n' ' ' <<<"$novye")"
  return 1
}
