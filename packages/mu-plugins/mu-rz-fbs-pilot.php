/** Путь раздела-приёмника от корня сайта, без крайних слешей. */
const RZ_FBS_RAZDEL_PUT = 'catalog/fbs-bloki';

/** Семнадцать схлопнутых марок. ФБС 24-4-6 здесь нет и быть не должно. */
function rz_fbs_shlopnutye() {
    return array(
        'fbs-12-3-6', 'fbs-12-4-3', 'fbs-12-4-6', 'fbs-12-5-6', 'fbs-12-6-6',
        'fbs-24-3-6', 'fbs-24-5-6', 'fbs-24-6-6',
        'fbs-6-3-6',  'fbs-6-4-3',  'fbs-6-4-6',  'fbs-6-5-6',
        'fbs-9-3-6',  'fbs-9-4-3',  'fbs-9-4-6',  'fbs-9-5-6',  'fbs-9-6-6',
    );
}

/** Те же семнадцать как пути от корня: 'catalog/fbs-bloki/fbs-12-3-6'. */
function rz_fbs_puti() {
    static $puti = null;
    if ($puti === null) {
        $puti = array();
        foreach (rz_fbs_shlopnutye() as $s) $puti[] = RZ_FBS_RAZDEL_PUT . '/' . $s;
    }
    return $puti;
}

/** Страница раздела или null. Ищется один раз за запрос. */
function rz_fbs_razdel() {
    static $r = null;
    if ($r === null) {
        $p = get_page_by_path(RZ_FBS_RAZDEL_PUT, OBJECT, 'page');
        $r = $p ? $p : false;
    }
    return $r ? $r : null;
}

/* ------------------------------------------------------------------ 1. якоря
 *
 * Строке таблицы раздела ставится id по слагу марки, чтобы редирект приводил
 * человека на его строку, а не в начало длинной страницы.
 *
 * Почему выводом, а не в содержимом страницы (задание разрешало и то, и другое).
 * Разбор таблиц в tools/rz-extract-products.php ищет строки шаблоном
 * '/<tr>(.*?)<\/tr>/su' — РОВНО «<tr>», без атрибутов. Появись id в разметке
 * страницы, ни одна строка бы не совпала, и ItemList раздела собрался бы
 * пустым при следующем же прогоне скрипта — молча, без ошибки. Правка вывода
 * оставляет содержимое в базе прежним и этой ловушки не создаёт.
 *
 * Приоритет 21 — после обёртки таблиц в mu-rz-theme.php (20) и блока
 * «Смотрите также» в mu-rz-related.php (20): работаем по готовой разметке и
 * не мешаем подстановке их временных меток.
 *
 * Только раздел ФБС: это пилот, другие разделы не трогаем.
 */

/** «ФБС 24-3-6» -> «fbs-24-3-6». Карта та же, что в tools/rz-extract-products.php. */
function rz_fbs_slug($s) {
    $map = array(
        'а'=>'a','б'=>'b','в'=>'v','г'=>'g','д'=>'d','е'=>'e','ё'=>'e','ж'=>'zh','з'=>'z',
        'и'=>'i','й'=>'y','к'=>'k','л'=>'l','м'=>'m','н'=>'n','о'=>'o','п'=>'p','р'=>'r',
        'с'=>'s','т'=>'t','у'=>'u','ф'=>'f','х'=>'h','ц'=>'c','ч'=>'ch','ш'=>'sh','щ'=>'sch',
        'ъ'=>'','ы'=>'y','ь'=>'','э'=>'e','ю'=>'yu','я'=>'ya',
    );
    $s = mb_strtolower(trim($s));
    $s = strtr($s, $map);
    $s = preg_replace('/[\s_\.\x{00A0}]+/u', '-', $s);
    return trim(preg_replace('/-+/', '-', $s), '-');
}

add_filter('the_content', function ($html) {
    if (is_admin() || is_feed() || !is_page()) return $html;
    if (strpos($html, '<tr') === false) return $html;

    $razdel = rz_fbs_razdel();
    $tek = get_queried_object();
    if (!$razdel || !($tek instanceof WP_Post) || (int) $tek->ID !== (int) $razdel->ID) return $html;

    return preg_replace_callback(
        '#<tr(\s[^>]*)?>(\s*<td\b[^>]*>(.*?)</td>)#su',
        function ($m) {
            /* Свой id у строки уже есть — чужую разметку не перебиваем. */
            if (!empty($m[1]) && preg_match('/\bid\s*=/i', $m[1])) return $m[0];
            $slug = rz_fbs_slug(wp_strip_all_tags($m[3]));
            /* Марка ряда и ничего кроме: «fbs-24-3-6». Не совпало — строка не
               наша (итоговая, служебная, чужая таблица), id не ставим. */
            if (!preg_match('/^fbs-\d{1,2}-\d{1,2}-\d{1,2}$/', $slug)) return $m[0];
            return '<tr id="' . esc_attr($slug) . '"' . (isset($m[1]) ? $m[1] : '') . '>' . $m[2];
        },
        $html
    );
}, 21);

/* -------------------------------------------------------------- 2. редиректы
 *
 * Каждая из семнадцати карточек -> раздел с якорем на свою строку, код 301.
 * Тем же способом, что /home/ в задании 031: template_redirect, по слагу.
 *
 * Сверка с page_on_front обязательна: если главной когда-нибудь назначат одну
 * из этих страниц, без неё получится вечный редирект.
 */
add_action('template_redirect', function () {
    if (!is_page()) return;
    $p = get_queried_object();
    if (!($p instanceof WP_Post)) return;
    if (!in_array($p->post_name, rz_fbs_shlopnutye(), true)) return;

    $razdel = rz_fbs_razdel();
    if (!$razdel || (int) $p->post_parent !== (int) $razdel->ID) return;
    if ((int) $p->ID === (int) get_option('page_on_front')) return;

    wp_redirect(get_permalink($razdel->ID) . '#' . $p->post_name, 301);
    exit;
});

/* ------------------------------------------------------------ 3. карта сайта
 *
 * Семнадцать адресов из карты убираются: оставить в ней адрес, который отдаёт
 * 301, — значит самим звать робота на редирект. Тем же фильтром, каким убрана
 * /home/: Rank Math выбрасывает запись, если вернуть пустое
 * (class-post-type.php: if (empty($url)) continue).
 *
 * Сверяем по адресу записи, а не по полям объекта: Rank Math отдаёт в фильтр
 * объект своей выборки, и набор полей в нём от версии к версии разный, а
 * loc есть всегда — по нему запись в карту и попадает.
 */
add_filter('rank_math/sitemap/entry', function ($url, $type, $object) {
    if ($type !== 'post' || !is_array($url) || empty($url['loc'])) return $url;
    $put = trim((string) parse_url($url['loc'], PHP_URL_PATH), '/');
    return in_array($put, rz_fbs_puti(), true) ? array() : $url;
}, 10, 3);
