#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Задание 023, раздел «Сверить перед заливкой». Точечные правки текста пакета
packages/vp-03.json перед заливкой. Каждое «было» обязано встретиться в
содержимом ровно один раз, иначе правка не применяется и печатается ошибка.

Основание каждой правки — таблица 56 марок на странице раздела
/catalog/plity-perekrytiya-kanalov-vp/ (та же, по которой сверялись данные
пакета vp-01 в задании 020). Ничего, кроме перечисленного ниже, не меняется.

Запуск: python3 tools/w023/pravki-vp-03.py [packages/vp-03.json]
"""
import json, os, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PKG = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'packages', 'vp-03.json')

PRAVKI = [
    # (слаг, было, стало, почему)
    ('vp-25-6',
     '<h2>Почему она вдвое дороже ВП 22-6</h2>',
     '<h2>Почему она на 72 % дороже ВП 22-6</h2>',
     'заголовок обещал двукратную разницу, в тексте под ним и в прайсе — 72 % '
     '(5 140 против 2 990)'),

    ('vp-25-6',
     'а ВП 25-6 и следующие за ней — уже 220 мм',
     'а ВП 25-6 и ВП 28-6 — уже 220 мм',
     'в узком ряду за ВП 28-6 идут ВП 49-6 и ВП 55-6 с толщиной 400 мм, '
     'а не 220'),

    ('vp-28-6',
     'Дальше в узком ряду типоразмеров нет: за 2800 мм ряд продолжается только '
     'в исполнениях шириной 1200 и 1800 мм.',
     'Между 2800 и 4900 мм в ширине 600 типоразмеров нет — там ряд продолжается '
     'в исполнениях шириной 1200 и 1800 мм. Дальше узкий ряд возобновляется на '
     'ВП 49-6 (4900 мм, 2520 кг) и ВП 55-6 (5500 мм, 3180 кг), но уже с толщиной '
     '400 мм.',
     'в таблице раздела есть ВП 49-6 и ВП 55-6 шириной 600 мм — утверждение '
     '«дальше типоразмеров нет» противоречит собственному прайсу сайта'),

    ('vp-37-12',
     'В ряду ВП толщина меняется трижды: 160 мм у коротких плит, 220 у средних, '
     '260 у ряда 31–34 и 320 начиная с 37. ВП 37-12 — первая марка самой толстой '
     'группы.',
     'В ряду ВП толщина растёт ступенями: 160 мм у коротких плит, 220 у средних, '
     '260 у ряда 31–34, 320 у 37 и 40, 360 у 43 и 46, 400 у 49 и 55. '
     'ВП 37-12 — первая марка ступени 320 мм.',
     'самая толстая группа в ряду — 400 мм (ВП 49 и ВП 55), а не 320; '
     'у ВП 43 и ВП 46 толщина 360 мм'),
]

pkg = json.load(open(PKG, encoding='utf-8'))
items = {i['slug']: i for i in pkg['items']}

oshibok = 0
for slug, bylo, stalo, pochemu in PRAVKI:
    it = items.get(slug)
    if it is None:
        print('ОШИБКА: в пакете нет позиции', slug); oshibok += 1; continue
    n = it['content'].count(bylo)
    if n != 1:
        print('ОШИБКА: [%s] «%s…» встречается %d раз' % (slug, bylo[:40], n))
        oshibok += 1; continue
    do = len(it['content'])
    it['content'] = it['content'].replace(bylo, stalo)
    print('%-9s %d -> %d знаков  — %s' % (slug, do, len(it['content']), pochemu))

if oshibok:
    print('правок не применено, файл не тронут: ошибок', oshibok)
    sys.exit(1)

json.dump(pkg, open(PKG, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
print('правок применено:', len(PRAVKI), '->', PKG)
